// One-off generator for the thin page files: each view is rendered at its English path and
// under /[lang]/. Re-run after adding a view: node scripts/make-lang-pages.mjs
import fs from 'node:fs';
import path from 'node:path';

const pages = [
  // [English page file, view, getStaticPaths source]
  ['index.astro', 'Home', null],
  ['today.astro', 'Today', null],
  ['add.astro', 'Add', null],
  ['how-we-know.astro', 'HowWeKnow', null],
  ['p/[slug].astro', 'Event', 'event'],
  ['country/[country].astro', 'Country', 'country'],
  ['city/[cc]/[region]/[city].astro', 'City', 'city'],
  ['region/[region].astro', 'Hub', 'region'],
  ['topic/[topic].astro', 'Hub', 'topic'],
];

const paths = {
  event: {
    imports: "import { events } from '../lib/data';\nimport { hasLang } from '../i18n/event';",
    en: 'events.map((e) => ({ params: { slug: e.slug }, props: { e } }))',
    lang: 'events.filter((e) => hasLang(e, lang)).map((e) => ({ params: { lang, slug: e.slug }, props: { e } }))',
    props: 'e={Astro.props.e}',
  },
  country: {
    imports: "import { COUNTRIES } from '../lib/data';",
    en: 'COUNTRIES.map((c) => ({ params: { country: c.slug }, props: { c } }))',
    lang: 'COUNTRIES.map((c) => ({ params: { lang, country: c.slug }, props: { c } }))',
    props: 'c={Astro.props.c}',
  },
  city: {
    imports: "import { cities } from '../lib/data';",
    en: "[...cities].map(([key, list]) => { const [cc, region, city] = key.split('/'); return { params: { cc, region, city }, props: { list } }; })",
    lang: "[...cities].map(([key, list]) => { const [cc, region, city] = key.split('/'); return { params: { lang, cc, region, city }, props: { list } }; })",
    props: 'list={Astro.props.list}',
  },
  region: {
    imports: "import { HUBS } from '../lib/data';",
    en: "HUBS.filter((h) => h.path.startsWith('/region/')).map((h) => ({ params: { region: h.path.split('/')[2] }, props: { h } }))",
    lang: "HUBS.filter((h) => h.path.startsWith('/region/')).map((h) => ({ params: { lang, region: h.path.split('/')[2] }, props: { h } }))",
    props: 'h={Astro.props.h}',
  },
  topic: {
    imports: "import { HUBS } from '../lib/data';",
    en: "HUBS.filter((h) => h.path.startsWith('/topic/')).map((h) => ({ params: { topic: h.path.split('/')[2] }, props: { h } }))",
    lang: "HUBS.filter((h) => h.path.startsWith('/topic/')).map((h) => ({ params: { lang, topic: h.path.split('/')[2] }, props: { h } }))",
    props: 'h={Astro.props.h}',
  },
};

const root = path.resolve('src/pages');
for (const [file, view, kind] of pages) {
  for (const localized of [false, true]) {
    const rel = localized ? path.join('[lang]', file) : file;
    const depth = rel.split(/[\\/]/).length; // pages/ + subfolders
    const up = '../'.repeat(depth);
    const fix = (s) => s.replaceAll("'../", `'${up}`);
    const p = kind ? paths[kind] : null;
    const lines = ['---', `// Generated by scripts/make-lang-pages.mjs — the page body lives in src/views/${view}.astro.`];
    lines.push(`import View from '${up}views/${view}.astro';`);
    if (localized) lines.push(`import { OTHER_LANGS } from '${up}i18n';`);
    if (p) lines.push(fix(p.imports));
    if (localized && !p) lines.push('export function getStaticPaths() {\n  return OTHER_LANGS.map((lang) => ({ params: { lang } }));\n}');
    if (localized && p) lines.push(`export function getStaticPaths() {\n  return OTHER_LANGS.flatMap((lang) => ${p.lang});\n}`);
    if (!localized && p) lines.push(`export function getStaticPaths() {\n  return ${p.en};\n}`);
    lines.push('---', `<View ${p ? p.props : ''} />`.replace(' />', ' />').replace('  />', ' />'));
    const out = path.join(root, rel);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, lines.join('\n') + '\n');
    console.log('wrote', path.relative(process.cwd(), out));
  }
}
